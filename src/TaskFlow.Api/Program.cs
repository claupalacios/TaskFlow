using System.Text.Json.Serialization;
using Microsoft.EntityFrameworkCore;
using TaskFlow.Api.Auth;
using TaskFlow.Api.Controllers;
using TaskFlow.Api.Errors;
using TaskFlow.Api.OpenApi;
using TaskFlow.Application.Auth;
using TaskFlow.Application.Tasks;
using TaskFlow.Application.Users;
using TaskFlow.Infrastructure.Persistence;
using TaskFlow.Infrastructure.Security;

var builder = WebApplication.CreateBuilder(args);

// ---- Composition root: the only place that knows about Infrastructure. ----

// Read when the context is first resolved, so configuration overrides (tests, env vars) apply.
// Also the design-time entry point for `dotnet ef` (Api is the startup project).
builder.Services.AddDbContext<AppDbContext>((sp, options) =>
    options.UseSqlite(sp.GetRequiredService<IConfiguration>().GetConnectionString("TaskFlow")));

builder.Services.AddSingleton(TimeProvider.System);
builder.Services.AddScoped<ITaskRepository, TaskRepository>();
builder.Services.AddScoped<IUserRepository, UserRepository>();
builder.Services.AddScoped<ITaskService, TaskService>();
builder.Services.AddScoped<IAuthService, AuthService>();
builder.Services.AddSingleton<IPasswordHasher, PasswordHasher>();
builder.Services.AddSingleton<ITokenService, JwtTokenService>();
builder.Services.AddScoped<DbSeeder>();

builder.Services.AddJwtAuthentication();

builder.Services.AddControllers()
    .AddJsonOptions(options => options.JsonSerializerOptions.Converters.Add(new JsonStringEnumConverter()));

builder.Services.AddProblemDetails();
builder.Services.AddExceptionHandler<ProblemDetailsExceptionHandler>();

// Two APIs, two OpenAPI documents; controllers pick theirs with [ApiExplorerSettings(GroupName)].
builder.Services.AddOpenApi(ApiDocuments.Tasks, options => options.AddBearerSecurity());
builder.Services.AddOpenApi(ApiDocuments.Identity, options => options.AddBearerSecurity());

var app = builder.Build();

// Automatic migration and demo data are for development and demos only (see appsettings.Development.json).
// Other environments apply migrations as an explicit deployment step.
if (app.Configuration.GetValue<bool>("Database:MigrateOnStartup"))
{
    await using var scope = app.Services.CreateAsyncScope();
    await scope.ServiceProvider.GetRequiredService<AppDbContext>().Database.MigrateAsync();

    if (app.Configuration.GetValue<bool>("Database:SeedDemoData"))
    {
        await scope.ServiceProvider.GetRequiredService<DbSeeder>().SeedAsync(CancellationToken.None);
    }
}

app.UseExceptionHandler();
app.UseHttpsRedirection();

app.UseAuthentication();
app.UseAuthorization();

app.MapOpenApi();
if (app.Environment.IsDevelopment())
{
    // UI only: it renders the documents generated by AddOpenApi(), one per API.
    app.UseSwaggerUI(options =>
    {
        options.SwaggerEndpoint($"/openapi/{ApiDocuments.Tasks}.json", "Tasks API v1");
        options.SwaggerEndpoint($"/openapi/{ApiDocuments.Identity}.json", "Identity API v1");
        options.EnablePersistAuthorization();
    });
}

app.MapControllers();

app.Run();
